"use client";
import { useState, type FormEvent } from "react";
import type { Answer, Message } from "@/contracts/api";
import { useWorkspace } from "@/lib/store";
import { useResource, useTask } from "@/lib/resources";
import { Badge, Button, PageHeader } from "../ui";
import { ErrorNotice, Loading, TaskNotice } from "../async-state";
import { Transcript } from "../transcript";
import { EvidenceList } from "../evidence";
import { SourceInspector } from "../knowledge-tools";
import { CorrectionDialog } from "../correction-dialog";
export function Playground({ embedded = false }: { embedded?: boolean }) {
  const { api, workspaceId: w, detail, owner } = useWorkspace();
  const [mode, setMode] = useState<"draft" | "published">("draft"),
    [conversationId, setConversationId] = useState<string | null>(null),
    [question, setQuestion] = useState(""),
    [pendingQuestion, setPendingQuestion] = useState(""),
    [answer, setAnswer] = useState<Answer | null>(null);
  const [inspect, setInspect] = useState<{
      id: string;
      version: string;
    } | null>(null),
    [correction, setCorrection] = useState<{
      question: string;
      message: Message;
    } | null>(null);
  const task = useTask(`${w}:${mode}`);
  const conversation = useResource(
    api,
    conversationId ? `/workspaces/${w}/conversations/${conversationId}` : null,
    (s) => api.conversation(w, conversationId!, s),
  );
  function reset() {
    task.cancel();
    setConversationId(null);
    setAnswer(null);
    setPendingQuestion("");
  }
  async function ask(value: string) {
    if (!value.trim() || task.busy) return;
    const text = value.trim();
    setQuestion("");
    setPendingQuestion(text);
    setAnswer(null);
    await task.run(async (signal) => {
      if (mode === "published" && !detail?.agent.publishedReleaseId)
        throw new Error(
          "Publish an approved release before using published preview.",
        );
      const accepted = await api.preview(
        w,
        {
          question: text,
          ...(conversationId ? { conversationId } : {}),
          ...(mode === "published"
            ? { releaseId: detail!.agent.publishedReleaseId! }
            : {}),
        },
        signal,
      );
      if (signal.aborted) return;
      task.setStatus(
        `Answer job ${accepted.jobId}: queued. No answer has been delivered.`,
      );
      const result = await api.waitForJob<Answer>(
        w,
        accepted.jobId,
        signal,
        (job) => task.setStatus(`Answer job ${job.id}: ${job.state}`),
      );
      if (!signal.aborted) {
        setConversationId(result.conversationId);
        setAnswer(result);
        setPendingQuestion("");
        conversation.reload();
        task.setStatus(`Answer completed against release ${result.releaseId}.`);
      }
    });
  }
  function submit(event: FormEvent) {
    event.preventDefault();
    ask(question);
  }
  const currentMessage = conversation.data?.messages.find(
    (m) => m.id === answer?.messageId,
  );
  return (
    <div className={`page-enter ${embedded ? "embedded-playground" : ""}`}>
      {!embedded && (
        <PageHeader
          eyebrow="A LITTLE ROOM TO EXPERIMENT"
          title="Ask a good question."
          description="Backend-generated draft and published answers with immutable source evidence."
        >
          <Button variant="secondary" onClick={reset}>
            New conversation
          </Button>
        </PageHeader>
      )}
      <div className="playground-layout">
        <section className="chat-panel">
          <div className="chat-panel-header">
            <div>
              <strong>{detail?.agent.draftConfig.name}</strong>
              <span>Replies are generated by the backend</span>
            </div>
            <label className="field">
              Knowledge version
              <select
                aria-label="Knowledge version"
                value={mode}
                onChange={(e) => {
                  reset();
                  setMode(e.target.value as typeof mode);
                }}
              >
                <option value="draft">Draft knowledge</option>
                <option
                  value="published"
                  disabled={!detail?.agent.publishedReleaseId}
                >
                  Published knowledge
                </option>
              </select>
            </label>
            <Badge>{mode}</Badge>
          </div>
          <div className="chat-messages">
            {!conversationId && !pendingQuestion && (
              <div className="chat-welcome">
                <h2>
                  Clarity starts
                  <br />
                  with a question.
                </h2>
                <p>
                  No simulated replies. Empty knowledge may return clarification
                  or handoff.
                </p>
                <div className="suggested-questions">
                  {detail?.agent.draftConfig.starterQuestions.map((q) => (
                    <button key={q} disabled={task.busy} onClick={() => ask(q)}>
                      {q}
                    </button>
                  ))}
                </div>
              </div>
            )}
            {conversation.loading && !conversation.data && (
              <Loading label="Loading saved transcript…" />
            )}
            <ErrorNotice
              error={conversation.error}
              retry={conversation.reload}
            />
            {conversation.data && (
              <Transcript
                messages={conversation.data.messages}
                busy={task.busy}
                inspect={(id, version) => setInspect({ id, version })}
                feedback={(m, rating) =>
                  task.run(async (signal) => {
                    await api.feedback(
                      w,
                      conversationId!,
                      { messageId: m.id, rating },
                      signal,
                    );
                    if (!signal.aborted)
                      task.setStatus("Feedback recorded by the backend.");
                  })
                }
                improve={
                  owner
                    ? (question, message) =>
                        setCorrection({ question, message })
                    : undefined
                }
              />
            )}{" "}
            {pendingQuestion && (
              <p className="state-notice">
                Submitted question: {pendingQuestion}
              </p>
            )}
            <TaskNotice task={task} />
          </div>
          <form onSubmit={submit} className="chat-composer">
            <input
              aria-label="Ask your agent"
              required
              maxLength={4000}
              value={question}
              onChange={(e) => setQuestion(e.target.value)}
              placeholder="Ask about your business…"
            />
            <Button disabled={task.busy || !question.trim()}>Send</Button>
          </form>
          <p className="chat-disclaimer">
            Draft preview never changes published visitor knowledge. Stopping
            observation does not cancel server work.
          </p>
        </section>
        <aside className="evidence-panel" aria-label="Current-turn evidence">
          <h2>Current-turn evidence</h2>
          <p>
            Exact backend-returned passages. Historical content is not replaced
            with current drafts.
          </p>
          <p>Release: {answer?.releaseId ?? "No completed turn"}</p>
          <p>
            Model: {answer?.model ?? "Not recorded"} · prompt:{" "}
            {answer?.promptVersion ?? "—"}
          </p>
          <EvidenceList
            evidence={currentMessage?.evidence ?? []}
            inspect={(id, version) => setInspect({ id, version })}
          />
        </aside>
      </div>
      <SourceInspector
        id={inspect?.id ?? null}
        versionId={inspect?.version}
        onClose={() => setInspect(null)}
      />
      {correction && (
        <CorrectionDialog
          key={correction.message.id}
          {...correction}
          onClose={() => setCorrection(null)}
        />
      )}
    </div>
  );
}
